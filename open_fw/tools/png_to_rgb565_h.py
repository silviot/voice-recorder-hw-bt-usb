#!/usr/bin/env python3
"""
Convert an 80x40 PNG image (e.g. assets/cassini_welcome_80x40.png) into a
C header defining a static const uint16_t RGB565 pixel array for open_fw.

SPDX-License-Identifier: MIT
"""
import argparse
from pathlib import Path
from PIL import Image


def rgb_to_rgb565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main() -> None:
    p = argparse.ArgumentParser(description="Convert PNG asset to C uint16_t RGB565 header.")
    p.add_argument("png", type=Path, help="Input PNG image")
    p.add_argument("--out", type=Path, required=True, help="Output C header path")
    p.add_argument("--symbol", default="CASSINI_SPLASH_80X40", help="C array symbol name")
    p.add_argument("--width", type=int, default=80, help="Target width (default 80)")
    p.add_argument("--height", type=int, default=40, help="Target height (default 40)")
    args = p.parse_args()

    img = Image.open(args.png).convert("RGB")
    if img.size != (args.width, args.height):
        img = img.resize((args.width, args.height), Image.Resampling.LANCZOS)

    px = img.load()
    vals = [rgb_to_rgb565(*px[x, y]) for y in range(args.height) for x in range(args.width)]

    lines = [
        "/* Auto-generated by open_fw/tools/png_to_rgb565_h.py — DO NOT EDIT */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define {args.symbol}_WIDTH  {args.width}u",
        f"#define {args.symbol}_HEIGHT {args.height}u",
        "",
        f"static const uint16_t {args.symbol}[{args.width}u * {args.height}u] = {{",
    ]
    for i in range(0, len(vals), 12):
        chunk = ", ".join(f"0x{v:04X}u" for v in vals[i : i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
