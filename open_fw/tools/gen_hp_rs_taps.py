#!/usr/bin/env python3
"""Generate bt_port/hp_rs_taps.h: Q15 polyphase tables for the headphones-mode resampler (bt_port/hp_sink.c,
docs/BT_A2DP_DESIGN.md §3.4). Pure Python (no numpy) so the table is reproducible anywhere; the firmware never
computes coefficients at run time, so host and ARM output are bit-identical.

  * Exact 3x (16 -> 48 kHz): 72-tap Kaiser-windowed sinc at the output rate, cut-off 0.42 x 16 kHz, split into
    3 phases x 24 taps (g_p[j] = 3 h[3j + p]).
  * General ratio: 16-tap windowed sinc evaluated at 65 fractional positions (64 phases + the closing one, so the
    resampler can interpolate linearly between neighbouring phases). Two cut-offs: 0.40 of the input rate (upsampling)
    and 0.40 x 44.1/48 of the input rate (48 -> 44.1 kHz downsampling).

Every phase row is normalised to an exact Q15 sum of 32768 (DC gain 1, rounding residue folded into the largest tap).
Usage: tools/gen_hp_rs_taps.py  (writes bt_port/hp_rs_taps.h). SPDX-License-Identifier: MIT"""
import math, os

def i0(x):
    s, t, k = 1.0, 1.0, 1
    while t > 1e-12 * s:
        t *= (x / (2 * k)) ** 2; s += t; k += 1
    return s

def kaiser(u, beta):  # u in [-1, 1]
    return i0(beta * math.sqrt(max(0.0, 1.0 - u * u))) / i0(beta) if abs(u) <= 1.0 else 0.0

def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)

def q15_row(row):
    s = sum(row)
    q = [int(round(v / s * 32768.0)) for v in row]
    q[max(range(len(q)), key=lambda i: abs(q[i]))] += 32768 - sum(q)
    assert sum(q) == 32768 and all(-32768 <= v <= 32767 for v in q)
    return q

def table_3x(taps=72, fc=0.42 * 16000 / 48000, beta=7.0):
    c = (taps - 1) / 2.0
    h = [2 * fc * sinc(2 * fc * (n - c)) * kaiser((n - c) / (c + 1), beta) for n in range(taps)]
    return [q15_row([h[3 * j + p] for j in range(taps // 3)]) for p in range(3)]

def table_gen(fc, taps=16, phases=64, beta=6.0):
    half = taps / 2.0
    rows = []
    for p in range(phases + 1):
        mu = p / phases
        # output at input time n + mu from x[n - 7 + j], j = 0..15: distance t = mu + 7 - j
        rows.append(q15_row([2 * fc * sinc(2 * fc * (mu + (half - 1) - j)) * kaiser((mu + (half - 1) - j) / half, beta)
                             for j in range(taps)]))
    return rows

def emit(name, rows):
    out = ["static const int16_t %s[%d][%d] = {" % (name, len(rows), len(rows[0]))]
    for r in rows:
        out.append("    {" + ", ".join("%d" % v for v in r) + "},")
    out.append("};")
    return "\n".join(out)

here = os.path.dirname(os.path.abspath(__file__))
dst = os.path.join(here, "..", "bt_port", "hp_rs_taps.h")
body = ["/* Generated by tools/gen_hp_rs_taps.py - do not edit. Q15, every row sums to 32768. SPDX-License-Identifier: MIT */",
        "#ifndef HP_RS_TAPS_H", "#define HP_RS_TAPS_H", "#include <stdint.h>",
        "#define HP_RS3_TAPS 24", "#define HP_RSG_TAPS 16", "#define HP_RSG_PHASES 64", "",
        "/* exact 3x: phase p (0..2) of output 3m+p, tap j applies to x[m - j] */", emit("hp_rs3_taps", table_3x()), "",
        "/* general, upsampling: cut-off 0.40 x input rate; row p = position p/64, tap j applies to x[n - 7 + j] */",
        emit("hp_rsg_up_taps", table_gen(0.40)), "",
        "/* general, 48 -> 44.1 kHz downsampling: cut-off 0.40 x 44.1/48 of the input rate */",
        emit("hp_rsg_down_taps", table_gen(0.40 * 44100 / 48000)), "", "#endif", ""]
open(dst, "w").write("\n".join(body))
print("wrote", os.path.relpath(dst))
