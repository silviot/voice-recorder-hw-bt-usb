#!/usr/bin/env python3
"""Generate tests/vectors/hmac_drbg_sha256_cavp.h from NIST CAVP HMAC_DRBG.rsp files.

Source: NIST CAVP "drbgtestvectors.zip" (DRBG 800-90A), inner archives drbgvectors_no_reseed.zip and
drbgvectors_pr_false.zip, file HMAC_DRBG.rsp. Only [SHA-256] groups are used; COUNT 0..N-1 of each group.

Usage: tools/gen_hmac_drbg_vectors.py NO_RESEED.rsp PR_FALSE.rsp [N] > tests/vectors/hmac_drbg_sha256_cavp.h
"""
import sys

FIELDS = ("EntropyInput", "Nonce", "PersonalizationString", "EntropyInputReseed", "AdditionalInputReseed",
          "AdditionalInput", "ReturnedBits")


def parse(path, n_per_group):
    vectors, in_sha256, cur, count_in_group = [], False, None, 0
    for raw in open(path, encoding="ascii"):
        line = raw.strip()
        if line.startswith("[") and "=" not in line:
            in_sha256 = line == "[SHA-256]"
            count_in_group = 0
            continue
        if line.startswith("[") and "=" in line:
            if line.startswith("[PredictionResistance"):
                count_in_group = 0  # a new parameter group starts
            continue
        if not in_sha256 or not line or "=" not in line:
            continue
        key, val = (x.strip() for x in line.split("=", 1))
        if key == "COUNT":
            cur = {"AdditionalInput": []}
            continue
        if cur is None:
            continue
        if key == "AdditionalInput":
            cur["AdditionalInput"].append(val)
        else:
            cur[key] = val
        if key == "ReturnedBits":
            if count_in_group < n_per_group:
                vectors.append(cur)
            count_in_group += 1
            cur = None
    return vectors


def c_bytes(hexstr):
    b = bytes.fromhex(hexstr)
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}" if b else "{0}", len(b)


def emit(name, vecs, reseed):
    out = [f"static const hmac_drbg_vec_t {name}[] = {{"]
    for v in vecs:
        parts = []
        for f in ("EntropyInput", "Nonce", "PersonalizationString", "EntropyInputReseed", "AdditionalInputReseed"):
            h = v.get(f, "") if (reseed or "Reseed" not in f) else ""
            arr, n = c_bytes(h)
            parts.append(f"(const uint8_t[]){arr}, {n}")
        a1, n1 = c_bytes(v["AdditionalInput"][0])
        a2, n2 = c_bytes(v["AdditionalInput"][1])
        rb, nr = c_bytes(v["ReturnedBits"])
        parts += [f"(const uint8_t[]){a1}, {n1}", f"(const uint8_t[]){a2}, {n2}", f"(const uint8_t[]){rb}, {nr}",
                  "1" if reseed else "0"]
        out.append("    { " + ",\n      ".join(parts) + " },")
    out.append("};")
    return "\n".join(out)


def main():
    no_reseed, pr_false = sys.argv[1], sys.argv[2]
    n = int(sys.argv[3]) if len(sys.argv) > 3 else 3
    a, b = parse(no_reseed, n), parse(pr_false, n)
    assert a and b, "no SHA-256 vectors found"
    print("/* GENERATED by tools/gen_hmac_drbg_vectors.py from NIST CAVP drbgtestvectors.zip (HMAC_DRBG.rsp, [SHA-256],")
    print(f" * first {n} COUNTs per parameter group): {len(a)} no-reseed + {len(b)} PredictionResistance=False vectors.")
    print(" * Procedure (CAVP): instantiate(entropy, nonce, pers); [reseed(entropy_reseed, addl_reseed)];")
    print(" * generate(addl[0]) discarding output; generate(addl[1]) == returned. Do not edit. */")
    print("#pragma once\n#include <stdint.h>\n#include <stddef.h>")
    print("typedef struct {\n    const uint8_t *entropy; size_t entropy_len; const uint8_t *nonce; size_t nonce_len;")
    print("    const uint8_t *pers; size_t pers_len; const uint8_t *entropy_reseed; size_t entropy_reseed_len;")
    print("    const uint8_t *addl_reseed; size_t addl_reseed_len; const uint8_t *addl1; size_t addl1_len;")
    print("    const uint8_t *addl2; size_t addl2_len; const uint8_t *returned; size_t returned_len; int reseed;\n} hmac_drbg_vec_t;")
    print(emit("k_hmac_drbg_no_reseed", a, False))
    print(emit("k_hmac_drbg_pr_false", b, True))


if __name__ == "__main__":
    main()
