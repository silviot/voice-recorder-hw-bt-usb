#!/usr/bin/env python3
"""Generate open_fw/bt_port/sdkconfig.h from Bluedroid's Kconfig.

Needs: `pip install kconfiglib` and an ESP-IDF checkout (IDF_PATH) at the pinned SHA
recorded in third_party/bluedroid/PORTING_NOTES.md (only components/bt is read).
Usage: IDF_PATH=/path/to/esp-idf tools/gen_bluedroid_config.py [extra.defaults ...]
SPDX-License-Identifier: MIT
"""
import os, re, sys, shutil, tempfile, kconfiglib

def sanitized_idf(idf):
    """Copy components/bt Kconfig files, dropping ESP-IDF-only Kconfig extensions
    (e.g. `warning "..."`) that stock kconfiglib cannot parse."""
    tmp = tempfile.mkdtemp(prefix="bdcfg_")
    base = os.path.join(idf, "components", "bt")
    for root, _, files in os.walk(base):
        for f in files:
            if f == "Kconfig" or f.endswith(".in") and "Kconfig" in f:
                dst = os.path.join(tmp, os.path.relpath(os.path.join(root, f), idf))
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                with open(os.path.join(root, f), errors="replace") as fh:
                    lines = [l for l in fh if not re.match(r"\s*warning\s+\"", l)]
                open(dst, "w").writelines(lines)
    return tmp

here = os.path.dirname(os.path.abspath(__file__))
port = os.path.join(here, "..", "bt_port")
os.environ["IDF_PATH"] = sanitized_idf(os.environ["IDF_PATH"])
os.environ.setdefault("srctree", port)
kc = kconfiglib.Kconfig(os.path.join(port, "Kconfig.wrap"), warn=False)
for frag in [os.path.join(port, "sdkconfig.defaults")] + ([] if os.environ.get("BT_LOG_TRACE") else [os.path.join(port, "sdkconfig.nolog")]) + sys.argv[1:]:
    kc.load_config(frag, replace=False)
kc.write_autoconf(os.path.join(port, "sdkconfig.h"),
                  header="/* Generated by tools/gen_bluedroid_config.py - do not edit */\n")
kc.write_config(os.path.join(port, "sdkconfig.generated"))
print("wrote sdkconfig.h:", sum(1 for s in kc.unique_defined_syms if s.str_value not in ("n", "")), "symbols set")
