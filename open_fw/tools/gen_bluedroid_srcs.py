#!/usr/bin/env python3
"""Extract the Bluedroid + common source list from the vendored CMakeLists, honouring
simple `if(CONFIG_X)`/`endif()` guards using bt_port/sdkconfig.h. Writes bt/bluedroid_srcs.mk.
SPDX-License-Identifier: MIT"""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, ".."))
bd = os.path.join(root, "third_party", "bluedroid")
cfg = {}
for l in open(os.path.join(root, "bt_port", "sdkconfig.h")):
    m = re.match(r"#define (CONFIG_\w+)\s*(.*)", l)
    if m: cfg[m.group(1)] = m.group(2).strip() or "1"
def evalc(cond):
    cond = cond.replace("(", " ( ").replace(")", " ) ")
    out = []
    for t in cond.split():
        if t in ("AND", "OR", "NOT", "(", ")"): out.append({"AND":"and","OR":"or","NOT":"not"}.get(t, t))
        elif t.startswith("CONFIG_"): out.append("True" if t in cfg else "False")
        else: out.append("True" if t in ("1","ON","TRUE") else "False")
    return eval(" ".join(out))
EXCLUDE = ("ble_log/", "bt_hci_log_insights", "blufi", "esp_blufi_api", "esp_gap_ble_api", "esp_ble_ead",
           # A2DP source only (OPENFW_A2DP_SOURCE_ONLY): no SBC decoder / PLC, no sink files
           "external/sbc/decoder", "external/sbc/plc", "btc_a2dp_sink", "bta_av_sbc_dec")
def parse(path, base):
    srcs, stack = [], []
    lines, buf = [], ""
    for raw in open(path):
        buf = (buf + " " + raw.strip()) if buf else raw.strip()
        if buf.startswith("if(") and buf.count("(") != buf.count(")"): continue
        lines.append(buf); buf = ""
    for line in lines:
        s = line.strip()
        m = re.match(r"if\((.*)\)\s*$", s)
        if m: stack.append(evalc(m.group(1)) if "CONFIG_" in m.group(1) else False); continue
        if s.startswith("elseif") or s.startswith("else"): 
            stack[-1] = not stack[-1]; continue
        if s.startswith("endif"): stack.pop(); continue
        m = re.search(r'"\$\{CMAKE_CURRENT_LIST_DIR\}/(.+\.c)"', s)
        # skip lines inside function() bodies / false guards
        if m and all(stack):
            srcs.append(os.path.normpath(os.path.join(base, m.group(1))))
    return srcs
# Only parse the srcs sections (after the first top-level `list(APPEND ..._srcs`)
def section(path, marker):
    txt = open(path).read(); i = txt.index(marker); open("/dev/null"); return txt[i:]
import tempfile
out = []
for rel, marker in (("host/bluedroid/CMakeLists.txt", "list(APPEND bluedroid_host_srcs"), ("common/CMakeLists.txt", "list(APPEND bt_common_srcs")):
    p = os.path.join(bd, rel); tmp = tempfile.NamedTemporaryFile("w", delete=False, suffix=".txt")
    tmp.write(section(p, marker)); tmp.close()
    out += parse(tmp.name, os.path.dirname(p)); os.unlink(tmp.name)
# KEEP: the vendored CMakeLists adds the SBC encoder only when CONFIG_BT_A2DP_USE_EXTERNAL_CODEC is off, but headphones
# mode encodes SBC itself through the external-codec path (bt_port/hp_sbc.c; docs/BT_A2DP_DESIGN.md §5.1).
KEEP = ("host/bluedroid/external/sbc/encoder/srce",)
for k in KEEP:
    d = os.path.join(bd, k)
    out += [os.path.join(d, f) for f in sorted(os.listdir(d)) if f.endswith(".c")]
out = sorted({os.path.relpath(f, root) for f in out if not any(x in f for x in EXCLUDE) and os.path.exists(f)})
# osal (freertos) is guarded by CONFIG_BT_OSAL_ENABLED in CMake; always needed for bt_prf_task etc.
osal = "third_party/bluedroid/common/osal/src/bt_osal_freertos.c"
if osal not in out: out.append(osal)
out.append("third_party/bluedroid/deps/esp_ringbuf/ringbuf.c")
with open(os.path.join(root, "bt", "bluedroid_srcs.mk"), "w") as f:
    f.write("# Generated by tools/gen_bluedroid_srcs.py - do not edit\nBLUEDROID_SRCS := \\\n")
    f.write(" \\\n".join("\t" + x for x in out) + "\n")
print(len(out), "sources")
