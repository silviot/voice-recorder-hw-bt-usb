void ui_i18n_set_lang(uint8_t lang)
{
    g_ui_lang = (lang < (uint8_t)UI_LANG_COUNT) ? lang : (uint8_t)UI_LANG_EN;
}

uint8_t ui_i18n_get_lang(void)
{
    uint8_t l = g_ui_lang;
    return (l < (uint8_t)UI_LANG_COUNT) ? l : (uint8_t)UI_LANG_EN;
}

const char *ui_lang_native_name(uint8_t lang)
{
    if (lang >= (uint8_t)UI_LANG_COUNT) {
        lang = (uint8_t)UI_LANG_EN;
    }
    return k_lang_names[lang];
}

const char *ui_tr_lang(uint8_t lang, ui_str_id_t id)
{
    if (lang >= (uint8_t)UI_LANG_COUNT) {
        lang = (uint8_t)UI_LANG_EN;
    }
    if ((unsigned)id >= (unsigned)UI_STR_COUNT) {
        return "";
    }
    const char *s = k_strings[lang][id];
    return s ? s : k_strings[UI_LANG_EN][id];
}

const char *ui_tr(ui_str_id_t id)
{
    return ui_tr_lang(ui_i18n_get_lang(), id);
}

const char *ui_i18n_weekday(uint8_t lang, uint8_t wd)
{
    if (lang >= (uint8_t)UI_LANG_COUNT) {
        lang = (uint8_t)UI_LANG_EN;
    }
    return k_wdays[lang][wd % 7u];
}

const char *ui_i18n_month(uint8_t lang, uint8_t month)
{
    if (lang >= (uint8_t)UI_LANG_COUNT) {
        lang = (uint8_t)UI_LANG_EN;
    }
    uint8_t idx = (month >= 1u && month <= 12u) ? (uint8_t)(month - 1u) : 0u;
    return k_months[lang][idx];
}
