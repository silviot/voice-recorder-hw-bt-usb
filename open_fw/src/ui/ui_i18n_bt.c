const char *ui_tr_bt_lang(uint8_t lang, ui_bt_str_id_t id)
{
    if ((unsigned)id >= (unsigned)UI_BT_STR_COUNT) {
        return "";
    }
    if (lang >= (uint8_t)UI_LANG_COUNT) {
        lang = (uint8_t)UI_LANG_EN;
    }
    const char *s = k_bt_strings[lang][id];
    return (s != 0 && s[0] != '\0') ? s : k_bt_strings[UI_LANG_EN][id];
}

const char *ui_tr_bt(ui_bt_str_id_t id)
{
    return ui_tr_bt_lang(ui_i18n_get_lang(), id);
}
