static void test_vectors(void)
{
    for (size_t i = 0; i < sizeof(k_vec) / sizeof(k_vec[0]); i++) {
        uint8_t q[48];
        CHECK(bt_p192_pubkey(k_vec[i].d, q) == 0, "%s: pubkey failed", k_vec[i].name);
        CHECK(memcmp(q, k_vec[i].q, 48) == 0, "%s: wrong public key", k_vec[i].name);
        CHECK(bt_p192_on_curve(k_vec[i].q), "%s: vector not on curve", k_vec[i].name);
    }
    printf("  %zu scalar multiplications match\n", sizeof(k_vec) / sizeof(k_vec[0]));
}

static void test_ranges(void)
{
    uint8_t d[24], q[48];
    memset(d, 0, sizeof(d));
    memset(q, 0xAA, sizeof(q));
    CHECK(bt_p192_pubkey(d, q) == -1, "d = 0 accepted");
    CHECK(q[0] == 0 && q[47] == 0, "output not zeroed on failure");
    memcpy(d, k_n, 24);
    CHECK(bt_p192_pubkey(d, q) == -1, "d = n accepted");
    memset(d, 0xFF, sizeof(d));
    CHECK(bt_p192_pubkey(d, q) == -1, "d = 2^192 - 1 accepted");

    uint8_t bad[48];
    memcpy(bad, k_vec[4].q, 48);
    bad[30] ^= 0x04u;
    CHECK(!bt_p192_on_curve(bad), "flipped Y bit still on curve");
    memset(bad, 0xFF, 24);                 /* X = 2^192 - 1 >= p */
    CHECK(!bt_p192_on_curve(bad), "X >= p accepted");
}

/* scripted RNG: candidates in order, then failure */
typedef struct {
    const uint8_t (*cand)[24];
    int n, pos, calls;
} script_t;

static int script_rng(void *ctx, void *out, size_t n)
{
    script_t *s = (script_t *)ctx;
    s->calls++;
    if (n != 24u || s->pos >= s->n) {
        return -1;
    }
    memcpy(out, s->cand[s->pos++], 24);
    return 0;
}

static void test_keygen(void)
{
    static uint8_t c[3][24];
    memset(c[0], 0, 24);                   /* 0: rejected */
    memcpy(c[1], k_n, 24);                 /* n: rejected */
    memcpy(c[2], k_vec[6].d, 24);          /* first random vector: accepted */
    script_t s = { (const uint8_t (*)[24])c, 3, 0, 0 };
    uint8_t d[24], q[48];
    CHECK(bt_p192_keygen(script_rng, &s, d, q) == 0, "keygen failed");
    CHECK(s.calls == 3, "expected 3 draws, got %d", s.calls);
    CHECK(memcmp(d, k_vec[6].d, 24) == 0 && memcmp(q, k_vec[6].q, 48) == 0, "keygen pair wrong");

    script_t f = { (const uint8_t (*)[24])c, 1, 0, 0 };   /* 0, then the RNG fails */
    memset(d, 0x55, sizeof(d));
    memset(q, 0x55, sizeof(q));
    CHECK(bt_p192_keygen(script_rng, &f, d, q) == -1, "keygen did not fail closed");
    int zero = 1;
    for (int i = 0; i < 24; i++) zero &= d[i] == 0;
    for (int i = 0; i < 48; i++) zero &= q[i] == 0;
    CHECK(zero, "keygen outputs not zeroed on failure");
    CHECK(bt_p192_keygen(NULL, NULL, d, q) == -1, "NULL rng accepted");
}

int main(void)
{
    test_vectors();
    test_ranges();
    test_keygen();
    if (g_fail) {
        printf("test_bt_p192: %d FAILURE(S)\n", g_fail);
        return 1;
    }
    printf("test_bt_p192: all tests passed\n");
    return 0;
}
